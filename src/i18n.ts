export type AppLang = 'fr' | 'en';

export function getInitialLang(): AppLang {
  try {
    const saved = localStorage.getItem('bitsure_lang');
    if (saved === 'en' || saved === 'fr') return saved;
  } catch {
    // ignore
  }
  return 'fr';
}

export function setSavedLang(lang: AppLang): void {
  try {
    localStorage.setItem('bitsure_lang', lang);
  } catch {
    // ignore
  }
}

